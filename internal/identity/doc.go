// Package identity 提供服務端的受信身份上下文與伺服器級角色授權判定。
//
// 為什麼要有這個套件（根 AGENTS.md §7：權限只由服務端可信身份與當前狀態決定）：
// 只要「這個請求是誰發的」「他能不能做這件事」在各個端點各寫一遍，就會出現
// 端點甲放行、端點乙漏判的兩套答案。本套件把這兩個問題收斂成一個值（Principal）
// 與一個判定入口（Authorize）：傳輸層只負責把認證結果換成 Principal，不再自己解釋角色。
//
// 三層主體必須分清，它們不是同一件事的三種寫法：
//   - 帳戶（Account）：穩定、跨活動的帳戶身份，標識取自 internal/account；
//   - 實際操作者（Principal）：這一次動作的發起主體，可以是帳戶、可以是配置裡的
//     Root，也可以是伺服器自身（啟動、CLI、背景任務）；
//   - 活動內身份（玩家檔案、NPC 操作者）：某個人在某個活動裡扮演誰。這一層仍未落地，
//     本套件因此不替它編造類別（拿 Root 或 server_admin 的檢查去頂替「他是這個活動的玩家」，
//     結果是「程式碼看起來把關了、實際把整個伺服器當成一個活動」）；
//     審計主體換不出類別的帳戶因此在 AuditActor 那條路上拿到明確的未實現錯誤。
//   - 已落地的一半是「活動管理權」：AuthorizeActivityScope 判定主體是否被指派為該活動的管理人，
//     指派清單由呼叫端從服務端查出的資料構造（identity.NewActivityGrants），
//     它不代替、也不等於上面那層「活動內扮演誰」的身份。
//
// 三條不可讓步：
//   - Principal 的欄位一律不匯出：構造只能走本套件的構造函式，所以「角色」「帳戶標識」
//     不可能來自請求本體或任意請求頭。零值即匿名——「忘了帶身分」是一種失敗，
//     不是一種預設。Root 主體更只能由真正比對過配置 Argon2id 憑據的結果換得，
//     生產側不存在「以 Root 身分跑一次」的捷徑（見 principal.go 的 RootProof）。
//   - 判定失敗分兩類：ErrNotAuthenticated 與 ErrPermissionDenied 是正常會發生的安全事件；
//     ErrInvalidPrincipal 與未實現邊界屬程式缺陷，不得被當成拒絕存取回報給使用者。
//   - 本套件不提供 HTTP 端點、不查資料庫、不決定會話如何撤銷：它只回答
//     「拿著這個主體，某件伺服器級的事能不能做」。
