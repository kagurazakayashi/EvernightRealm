// Package credential 提供 Argon2id 憑據雜湊的產生與安全校驗，
// 供組態中的 Root 憑據與資料庫中的普通帳戶憑據共用同一套語意。
//
// 邊界：本套件只做「明文 ↔ 編碼雜湊」的密碼學適配，不做網路登入、
// 不做找回、不做 PIN，也不替任何上層決定憑據策略（長度下限、改密週期等）。
// 上層（config、account、未來的會話服務）拿到的接口只有四类：
// 產生（Hash）、校驗（Verify）、升級識別（NeedsUpgrade）、
// 時間均衡（VerifyPlaceholder，供「帳戶不存在」分支消耗與真實校驗同階的成本）。
//
// 編碼採用 PHC 字串格式（RFC 9106 的形式），雜湊自帶算法名、版本與參數：
//
//	$argon2id$v=19$m=<KiB>,t=<時間成本>,p=<並行度>$<鹽><摘要>
//
// 鹽與摘要以無填補 base64（標準字母表）編碼。參數隨編碼走，校驗以編碼內
// 參數為準，因此升級參數檔不需要全量重寫既有憑據——NeedsUpgrade 只標記，
// 重寫時機由上層（如登入成功後）決定。
//
// 安全取向：
//   - 算法不自行發明，僅使用 golang.org/x/crypto/argon2（官方 Argon2id 實作）；
//   - 鹽由 crypto/rand 產生，每份憑據獨立；
//   - 校驗嚴格解析編碼並對參數設硬性上限，損壞或惡意編碼不可能要求
//     超出上限的記憶體或時間；校驗失敗一律以布爾值回報，解析細節不外洩；
//   - 比對使用恆定時間比較；
//   - 任何錯誤訊息、日誌與返回值都不含明文、鹽或完整雜湊。
