package httpapi

import (
	"encoding/json"
	"net/http"
)

// ErrorCode 為對外的穩定機器錯誤碼。
//
// 分段規劃（S02 決策）：1xxx 通用與協定層、2xxx 帳號與身分、3xxx 資產與帳務，
// 其餘分段隨端點實作細分。已發布的數值不得變更或重用。
type ErrorCode int

const (
	// CodeUnknown 表示未分類的內部錯誤；對外只回固定文案，不洩漏細節。
	CodeUnknown ErrorCode = 1000
	// CodeNotFound 表示請求的路徑不存在。
	CodeNotFound ErrorCode = 1001
	// CodeMethodNotAllowed 表示路徑存在，但不支援該 HTTP 方法。
	CodeMethodNotAllowed ErrorCode = 1002
	// CodePayloadTooLarge 表示請求體超過 server.max_body_bytes 上限。
	CodePayloadTooLarge ErrorCode = 1003
	// CodeInvalidBody 表示請求體無法解析（畸形 JSON、未知欄位、空本體或尾隨資料）。
	CodeInvalidBody ErrorCode = 1004
	// CodeUnsupportedMediaType 表示請求體不是 JSON 內容型別。
	CodeUnsupportedMediaType ErrorCode = 1005
	// CodeRequestTimeout 表示處理超過 server.request_timeout_ms 期限。
	CodeRequestTimeout ErrorCode = 1006
	// CodeNotReady 表示服務尚未就緒（依賴的資料庫無法回應），業務操作暫不可執行。
	CodeNotReady ErrorCode = 1007
	// CodeNoSpace 表示資料目錄所在卷的可用空間已低於設定下限：新的寫入被暫停。
	//
	// 與 CodeNotReady 分開是因為用戶端的處置不同：一個是「等一會兒再試」，
	// 另一個要有人去清磁碟或改下限，重試不會讓它自己變好（規格 AT-020）。
	// 下限未設時這個碼永遠不會出現。
	CodeNoSpace ErrorCode = 1008

	// —— 以下為 2xxx 帳號與身分分段（R1-009 起發布，數值不得變更或重用）。——

	// CodeInvalidCredentials 表示登入被拒。它是登入失敗時唯一的對外結論：
	// 「帳戶不存在」「口令錯誤」「訪客帳戶」「已禁用」「Root 憑據不符或未設定」
	// 全部收斂到這一個碼與同一句文案——外部因此沒有一枚可以枚舉帳戶的信號。
	// 後續步驟若加「嘗試次數過多請稍後再試」，必須是全帳戶同形的限流語意，
	// 不得出現「這個帳戶被鎖了」這種把內部原因放回回應的變體。
	CodeInvalidCredentials ErrorCode = 2001
	// CodeNotAuthenticated 表示請求沒有攜帶任何會話憑據（Cookie 與 Bearer 都沒有），
	// 而該端點需要身分。它與 CodeSessionInvalid 分開：一個是「沒帶」，
	// 另一個是「帶了但無效」，用戶端的處置文案不同（前者是首次登入引導）。
	CodeNotAuthenticated ErrorCode = 2002
	// CodeSessionInvalid 表示攜帶的會話憑據無效：形狀不合格、查無此會話、
	// 已被撤銷、已到期，或其主體此刻不可用（帳戶被禁用）。對內這些原因可區分，
	// 對外一律同一句「請重新登入」——持秘密的人不需要知道它是哪一半壞的。
	CodeSessionInvalid ErrorCode = 2003
	// CodeAuthMethodConflict 表示請求把兩種認證方式混在一起用：同時帶會話 Cookie 與
	// Bearer，或瀏覽器請求（帶 Origin）企圖用 Bearer 認證。混用的危害是 Cookie 請求
	// 借 Bearer 繞過來源校驗，因此這不是偏好問題，而是直接拒絕的缺陷信號。
	CodeAuthMethodConflict ErrorCode = 2004
	// CodeOriginForbidden 表示有副作用的請求來源未通過 CSRF 來源策略：
	// Origin 既非同源、也不在組態白名單內，或 Sec-Fetch-Site 宣告跨站。
	// 預檢放行與否不影響此判定——來源標頭不是身分授權（與 cors.go 同一取向）。
	CodeOriginForbidden ErrorCode = 2005
	// CodeLoginThrottled 表示該來源的登入失敗額度已打滿，正處於冷卻（HTTP 429，
	// 附 Retry-After）。它是「稍後再試」而不是「憑據不對」：冷卻到期後同一枚正確
	// 口令照常可登入。回應同樣只有一句固定文案——不指出被擋的是哪個帳戶、
	// 觸發的是來源×目標配對上限還是來源總量上限，與 2001 的不可枚舉要求同形。
	CodeLoginThrottled ErrorCode = 2006
	// CodeSessionStale 表示帶來的會話秘密是「上一代」的：它對應的會話還在，但已經
	// 換發過新秘密，因此這枚憑據換不出任何身份。
	//
	// 它與 CodeSessionInvalid 分開只為一件事：這一句失敗的處置是「重試」，
	// 不是「重新登入」——把一次正常換密說成一次登出，會把與輪換交錯的那條請求
	// 變成使用者的意外掉線。它不給任何訪問能力，也不給新秘密：落後一代的人
	// 本來就沒有資格知道新一代是什麼。舊秘密的失效依然是即時的。
	CodeSessionStale ErrorCode = 2007
	// CodeDeviceLimitReached 表示憑據正確，但該主體的有效會話名額已達伺服器策略的上限，
	// 這次登入整個沒有發生（沒簽發新會話，也沒撤銷任何既有會話）。
	//
	// 它與 CodeInvalidCredentials 分開只為一件事：這一次的失敗跟口令無關，
	// 把「你手上那個正確的口令」報成「憑據無效」會讓人對著對的口令反覆懷疑自己。
	// 它也與 CodeLoginThrottled 分開：限流等冷卻結束就有全新預算，名額則要等到
	// 某個會話被登出或到期——同一句「稍後再試」對兩者都不是準確的指引。
	// 回應不含上限值、現有會話數或任何裝置標識：那些屬伺服器的內部配置。
	CodeDeviceLimitReached ErrorCode = 2008
	// CodeDeviceNotFound 表示「我的裝置」定向撤銷指向的 device_id 不在本人的會話範圍內：
	// 它可能從未存在、已被清理，或本就是別的裝置／別人的裝置——三種情況一律同一個答案。
	//
	// 它存在只為給客戶端一句準確的「列表已陳舊，請重新整理」：使用者對著一份舊清單點撤銷，
	// 而那枚裝置其實已經不在，這既不是憑據問題（該重新登入），也不該謊報成撤銷成功。
	// 它絕不透露「這個 device_id 是否存在於他人名下」：device_id 是隨機 UUIDv7，
	// 猜中它已等同盲猜一枚憑據，把「不屬於你」與「不存在」收斂同形不損失任何合法性。
	CodeDeviceNotFound ErrorCode = 2009
	// CodePasswordChangeRequired 表示該帳戶帶有「首次登入必須改密」旗標，而這個端點
	// 不在改密必要入口之內：先完成改密（或登出），其他能力才重新的開放。
	//
	// 它存在是因爲強制改密必須是服務端的門，而不是頁面上的一句提示：只在界面攔、
	// 接口照常放行，等於給任何繞過界面的調用者留了正門。判定每請求現讀帳戶行，
	// 改密成功的下一條請求就拿到放行——旗標的解除因此不存在「改了密還被鎖着」的滯留。
	// 403 而不是 401：憑據本身有效（401 會錯指「重新登錄」能解決），
	// 缺的是完成改密這項義務。
	CodePasswordChangeRequired ErrorCode = 2010
	// CodePermissionDenied 表示身分可信、但這個身分沒有這件事所需要的權限。
	//
	// 它與 CodeNotAuthenticated（沒帶憑據）、CodeSessionInvalid（憑據換不出身分）分開，
	// 因為三句話的處置完全不同：一個要登入，一個要重登，而這一個什麼都不用重試——
	// 同一個人在同一臺裝置上再點一次，結果不會變。把它們混成 2002／2003 會讓客戶端
	// 把「你沒有這個權限」處理成「你被登出了」，而那是無緣無故把人踢回登入頁。
	//
	// 判定只可能來自服務端解析出的受信主體（見 internal/identity.Authorize）：
	// 請求裡沒有任何欄位可以把自己昇格，也沒有一條路把「帶著有效 Cookie 的普通帳戶」
	// 讀成 Root 或管理員。403 而不是 401：這一格問的不是憑據。
	// 回應不含「需要哪個角色」「還缺哪些權限」——那些屬伺服器的內部授權資料。
	CodePermissionDenied ErrorCode = 2011
	// CodeLoginNameTaken 表示要開設的登入名（正規化後）已被佔用。
	//
	// 它是可預期的業務衝突而不是故障：答案由 accounts 表的登入名唯一索引給出，
	// 因此「重複提交」「與併發的另一次開設撞鍵」「丟失回應後的重試」都不會產生第二個帳戶，
	// 只会拿到這一句。它與 CodeInvalidBody 分開：後者是要人改寫法，這裡改不了——
	// 那個名字已經是別人的了，要換的是名字而不是拼寫。
	//
	// 它只在 Root 的開設入口上出現（該入口本身經 NeedRoot 判定），因此不构成
	// 任何人可用的帳戶列舉信號：能收到這句話的人已經證明瞭自己是 Root，
	// 而 Root 本來就是帳戶目錄的所有者。回應不回顯既有帳戶的任何資料，也不回顯口令。
	CodeLoginNameTaken ErrorCode = 2012
	// CodeProfileConflict 表示編輯管理員資料所依據的現值已不是資料庫現值：整個編輯沒有發生。
	//
	// 它是可預期的併發結論而不是故障：兩個人對著同一份畫面改名時，後提交的必然發現
	// 「你看見的那個值已經不是現值」——比較-and-set 讓輸家一個字都不覆蓋（與 2012 的
	// 唯一索引兜底同一取向：正確性來自資料庫條件，不來自「先查後寫假裝窗口不存在」）。
	// 處置與 CodeDeviceNotFound（2009）同形：重新讀取服务端現值再決定，
	// 既不是憑據問題（該重新登入），也不該謊報成保存成功。
	// 回應不回顯雙方的任何值、不指出「現在的現值是什麼」——那是重讀詳情本來就該拿的資料，
	// 塞進錯誤信封只會多出「同一個欄位有兩個答案來源」的维护點。
	CodeProfileConflict ErrorCode = 2013
	// CodeAdminStatusConflict 表示停用／恢复管理员所依据的状态现值已不是数据库现值：
	// 整个操作没有发生——状态没改、会话没撤、审计没记。
	//
	// 它是可预期的并发结论而不是故障：两个入口对着同一份目录画面先后点停用，
	// 后到的那次必然发现「你确认时他活着，现在他已经不是了」——比较-and-set 让输家
	// 连一轮会话都不撤（与 2013 的显示名冲突同一取向：正确性来自数据库条件）。
	// 它不与 CodeProfileConflict 共用：两者的处置不同——一个重读那个字段再改，
	// 另一个要重读目标的整个可用性并重新走一次确认，把人手上那颗按钮再点一遍
	// 对第二种情况不是答案。重复操作（停用已停用者）也收敛到这里，不谎报成功：
	// 把「什么都没发生」说成「又停用了一次」，审计与真相就对不上。
	// 处置与 CodeDeviceNotFound（2009）同形：刷新目录／详情看服务器现值再决定。
	// 回应不回显目标的当前状态——那是重读本来就该拿到的资料。
	CodeAdminStatusConflict ErrorCode = 2014
	// CodeAdminDeleted 表示目標是已被軟刪除的管理員賬戶：本次操作沒有可發生的對象——
	// 狀態沒改、憑據沒換、會話沒撤、審計沒記。
	//
	// 它是可預期的處置結論而不是故障，也與 1001（查無此人／不在目錄）刻意分開：
	// 兩句話的處置完全不同——一個是「這個標識不在這本目錄裡，換個目標」，另一個是
	// 「你眼前這個人都已經被刪掉了，別再對他下任何寫入令」。把後者報成 1001，Root 會
	// 對着一個目錄裡明明列着的人反覆懷疑標識抄錯了；把重複刪除報成成功，則是在審計
	// 與真相之間造出一件沒發生過的事。
	//
	// 它同樣不與 2013/2014 共用：那兩者說的是「你依據的現值已過期，重讀再來一次」，
	// 而刪除是終態——重讀之後的答案是「他已經不在了」，再點一次那顆按鈕不是答案。
	// 可見範圍只有 Root（本組端點全部經 NeedRoot 判定），因此不構成任何人可用的
	// 賬戶枚舉信號。回應不回顯目標的任何字段值，也不回顯刪除時刻——那是重讀
	// 詳情本來就該拿到的資料。
	CodeAdminDeleted ErrorCode = 2015
	// CodeAccountPolicyModeUnavailable 表示送來的自註冊模式是已批准的名字，
	// 但它所需的准入通路在本伺服器版本尚未落地，因此策略不能記成這個值。
	//
	// 它與 CodeInvalidBody（1004）分開只為處置不同：1004 說的是「那個名字不存在，
	// 改寫法再來」，而這裡改寫法換不來任何結果——要等的是對應步驟把通路做出來。
	// 把兩者混成一句，界面就只能對 Root 念「請求不合法」，而 Root 明明填了一個
	// 他在規格裡見過的名字。
	//
	// 它也絕不降級成成功：把 invite 默默寫成 closed 或 open，等於伺服器對一個沒有實作的
	// 計畫給出兩種不同的說法。回應不回顯當前策略現值——
	// 那是重讀策略端點本來就該拿到的資料。
	CodeAccountPolicyModeUnavailable ErrorCode = 2016
	// CodeAccountCreationDisabled 表示這條帳戶建立通路此刻被伺服器策略關閉：
	// 請求本身合法、操作者的權限也確實足夠，缺的是伺服器對「開不開放這條通路」的現值。
	//
	// 它必須與 2011（權限不足）分開，因為兩句話的處置完全不同：2011 是「你的身分
	// 做不了這件事，再試一次也不會變」，這裡是「你有這個能力，但伺服器目前不許」——
	// 處置是請 Root 在帳戶建立策略裡把開關打開，而不是換身分或重新登入。
	// 也與 1004 分開：請求本體沒有任何可改的欄位，改寫法換不來結果。
	//
	// Root 走同一條端點時同被拒（開關不豁免任何主體），所以這句話也不構成
	// 「換個管理員帳號就有用」的暗示。回應不含開關現值與策略細節——
	// 那是只有 Root 經策略端點才該讀到的資料。
	CodeAccountCreationDisabled ErrorCode = 2017
	// CodeGuestUpgradeRequired 表示目標是訪戶帳戶：他今日沒有一般密碼可重置，
	// 沿這條通路寫入憑據等於替他完成一次訪戶→普通的升級綁定，而那不是本端點的職責。
	//
	// 它必須與已发布的三句分開，因為處置各不相同：1004 說的是「那個口令寫法不合規，
	// 改寫法再來」，對訪戶改寫法換不來任何結果；2011 說的是「你的身分做不了這件事」，
	// 而操作者的權限確實足夠；1001 說的是「他不在這本目錄裡，換個目標」，
	// 但本目錄按定義把訪戶列得進去，叫操作者換目標是誤導。
	// 要動的是身分而不是一欄口令，那條通路是同一本目錄下的
	// PUT /admin/accounts/{account_id}/upgrade（它自報動的是身分，而不是一欄口令），
	// 所以這句也不構成「再試一次就會成」的暗示：重複提交只會再拒一次。
	// 回應不回顯目標的類型細節以外的事，也不帶任何口令材料。
	CodeGuestUpgradeRequired ErrorCode = 2018
	// CodeSelfRegisterNameTaken 表示匿名自註冊選的登入名（正規化後）已被佔用：
	// 本次註冊整個沒有發生——帳戶沒多出來、審計沒記、憑據也沒落地。
	//
	// 它與需要已認證主體的 CodeLoginNameTaken（2012）刻意分開：2012 的既有合同寫明
	// 「只在 Root 的開設入口上出現」，不讓它順帶變成一枚匿名端點的回應。兩者說的
	// 是同一種業務衝突（那個名字是別人的，要換的是名字而不是拼寫），面向的卻是
	// 兩種完全不同的呼叫者與處置路徑，因此各有一枚碼。
	// 它也是可預期的業務結論而不是故障：答案由 accounts 表的登入名唯一索引給出，
	// 因此「重複提交」「與併發的另一次註冊撞鍵」都只會拿到這一句，不會產生第二個帳戶。
	//
	// 關於「存在性探測」：任何讓匿名者自行選一個唯一登入名的端點，結構上就是一部
	// 存在性探測器——一次成功即代表這個名字還沒被佔用，這不是措辭能掩蓋的，
	// 因此這裡如實回可判別的重名句讓正常用戶知道要換名字，而不是把回應整形成全同形。
	// 真正的批量防護來自緊限流（2006）與併發封頂（見 internal/selfregister），
	// 而不是靠謊報失敗。回應不回顯既有帳戶的任何資料，也不回顯口令。
	CodeSelfRegisterNameTaken ErrorCode = 2019
	// CodeNotAnApplication（HTTP 403）：憑據成立，但這一筆帳戶不是待審批的申請。
	//
	// 它只在 POST /auth/registration-status 上出現，而且只在「已經證明你是他本人」之後
	// 才可能回出來：查無此名、訪客帳戶與口令不符一律收斂成 2001（與登入同形），
	// 所以這條通路對「誰的名字存在」不新增任何信號，2020 也只對持有正確憑據的人說話。
	//
	// 它與 2011（PermissionDenied）分開是因為處置完全不同：2011 說的是「你的身分不夠」，
	// 而這裡問的恰恰不是權限——他登得進去（或根本沒申請過），處置是「走 /auth/login」，
	// 不是「去要一個更大的身分」。也不與 2017（策略未開放）共用：2017 描述的是伺服器狀態，
	// 一句「等 Root 打開」；2020 描述的是這個呼叫者的帳戶由哪條通路誕生，等誰都沒有用。
	CodeNotAnApplication ErrorCode = 2020
	// CodeApplicationDecided（HTTP 409）：這一筆註冊申請已經有過決定，本次審批整個沒有發生——
	// 狀態沒改、決定時刻沒寫、審計沒記。
	//
	// 它是可預期的併發與重複結論而不是故障，與 2014（停用／恢復的狀態衝突）同一族但不同一句話：
	// 2014 說的是「你確認時他的可用性已不是現值，重讀之後同一顆按鈕還可以再按一次」，
	// 而這裡重讀之後的答案是「他已經被決定過了」——那顆按鈕對這個目標不再存在，
	// 再按一次不會讓先前那個決定被撤銷，也不會把拒絕改成批准（用戶批准的單向決定）。
	// 兩個審核者同時按下時只有先提交的那一次有效，後到的拿到這一句，
	// 因此它同時擋住「悄悄覆蓋先前決定」這條路。
	//
	// 它不降級成 1001：那句是「這個人根本不在這本名冊上，換個目標」，而這裡目標就躺在名冊上，
	// 只是已經沒有第二顆按鈕；也不降級成 2011：審核者的權限確實足夠。
	// 回應不回顯是誰做的決定、不帶任何理由文本，也不回顯決定時刻——
	// 那些屬重讀名冊與 Root 域審計各自該給的資料，塞進錯誤信封只會多出一個「同一件事有兩個答案來源」的維護點。
	CodeApplicationDecided ErrorCode = 2021
	// CodeInviteAlreadyRevoked（HTTP 409）：這一枚伺服器級註冊邀請碼已經被撤銷，本次撤銷整個沒有發生——
	// 撤銷時刻沒改、已用次數沒動、審計沒記。
	//
	// 它是可預期的併發與重複結論而不是故障，與 2021（審批的「已有決定」）同一族但不同一句話：
	// 撤銷是一枚碼的單向終態——重讀之後的答案是「它已經不在有效那一側了」，對著同一枚已撤銷的碼
	// 再按一次那顆按鈕不會讓先前那次撤銷被撤銷，也不會把它改成別的時刻（用戶批准的終態規則）。
	// 兩個撤銷者同時按下時只有先提交的那一次有效，後到的拿到這一句，因此它同時擋住
	// 「悄悄改寫先前那個撤銷」這條路。
	//
	// 它不降級成 1001：那句是「這枚碼根本不在這本名冊上，換個目標」，而這裡目標就躺在名冊上，
	// 只是已經沒有第二顆按鈕；也不降級成 2011：撤銷者的權限確實足夠。
	// 回應不回顯是誰撤銷的、不帶任何理由文本，也不回顯明文碼——那些屬重讀名冊與 Root 域審計各自該給的資料，
	// 而明文碼從簽發之後就再沒有任何讀法能拿回來。
	CodeInviteAlreadyRevoked ErrorCode = 2022
	// CodeInviteRejected（HTTP 403）：策略開的是邀請碼自註冊，而这一次的邀請碼換不出一筆帳戶。
	//
	// 它把「完全沒帶碼」「碼形状不合」「這臺伺服器沒簽過這枚碼」「已撤銷」「已過期」「額度用滿」
	// 「併發下被另一筆註冊搶先耗盡」七種內部原因一律收斂成同一句話與同一個碼：呼叫端據回應分辨不出
	// 自己差的是哪一半，於是 POST /auth/register 不會變成一部「逐枚探測邀請碼有效性」的探測器——
	// 批量防護交給與開放模式同一條來源×登入名緊限流（2006）與派生併發封頂，而不是把回應整形（與
	// internal/selfregister 對登入名存在性的同一取向：探測性質不掩蓋，靠限流壓住）。
	//
	// 它刻意不與幾枚現成的碼混用：不降成 1004（那要人改寫法，對一枚本就無效或根本沒帶的碼改寫法換不來
	// 結果，會誤導人湊一個欄位再按一次）；不降成 2017（那句講的是「這條路沒開」，而路開著、是用錯憑證）；
	// 不併入 2019（那句是「名字被佔用」，把准入憑證與登入名兩件事混在一起會讓彼此可被對方探測）。
	// 也不回顯任何邀請碼相關資訊：明文碼、其 SHA-256 驗證材料、是哪一枚、剩餘額度、過期與撤銷時刻
	// 一概不在回應裡——那些屬 Root 重讀名冊才該拿到的資料，而明文碼自簽發後就再無讀法。
	CodeInviteRejected ErrorCode = 2023
	// CodeGuestNotUpgradable（HTTP 409）：目標此刻不是一個可升級的訪戶——
	// 他已是普通帳戶（重複升級），或他的登入能力此刻被停用。本次升級整個沒有發生：
	// 分類沒轉、憑據沒落地、會話沒撤、審計沒記。
	//
	// 它是目標形態的出局結論而不是故障，也與相鄰幾句刻意分開：
	// 2018 的方向恰好相反（他說的是「他是訪戶，重置口令要等升級通路」，
	// 而這條通路就是那個升級）；1001 說的是「他不在這本目錄裡，換個目標」，
	// 但這本目錄按定義把他列得進去；2011 說的是「你的身分做不了這件事」，
	// 而操作者的權限確實足夠；2014 說的是「你依據的現值已過期，重讀之後同一顆按鈕還可以再按」，
	// 而對「已轉正」的人重讀之後的答案是那顆按鈕已不存在。
	// 兩種內部原因（已轉正／已停用）收斂成同一句話是刻意的：界面在發起請求前就按
	// 服務端讀回的來源與狀態分岔，這枚碼在正路徑上只兜住繞過界面的直打與併發尾巴。
	// 可見範圍只有伺服器級管理員（本組端點全部經 NeedServerAdmin 判定），
	// 因此不構成任何人可用的帳戶枚舉信號。回應不回顯目標的現值，也不帶任何口令材料。
	CodeGuestNotUpgradable ErrorCode = 2024
)

// ErrorEnvelope 是所有錯誤回應的統一信封，也是錯誤回應格式的唯一權威定義。
//
// 欄位依 S02 決策固定為穩定數字錯誤碼、在地化使用者訊息、選用細節與請求關聯 ID；
// Details 供輸入驗證錯誤標示可公開的判定依據（如上限值、未知欄位名），
// 不得放入伺服器內部狀態；值為空時不出現在回應中。
type ErrorEnvelope struct {
	Code      ErrorCode      `json:"code"`
	Message   string         `json:"message"`
	Details   map[string]any `json:"details,omitempty"`
	RequestID string         `json:"request_id"`
}

// writeJSON 以 JSON 內容型別輸出回應；標頭送出後才編碼，編碼失敗無法再改寫狀態碼。
func writeJSON(w http.ResponseWriter, status int, payload any) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(payload)
}

// writeError 以統一信封輸出錯誤回應：狀態碼依 status，訊息依 Accept-Language 協商。
func writeError(w http.ResponseWriter, r *http.Request, code ErrorCode, status int) {
	writeErrorDetails(w, r, code, status, nil)
}

// writeErrorDetails 同 writeError，並附上選用細節（如解碼失敗原因、上限值）。
// details 僅限用戶端自身輸入相關資訊，不得帶入伺服器內部狀態或堆疊。
func writeErrorDetails(w http.ResponseWriter, r *http.Request, code ErrorCode, status int, details map[string]any) {
	writeJSON(w, status, ErrorEnvelope{
		Code:      code,
		Message:   messageFor(code, negotiateLocale(r.Header.Get("Accept-Language"))),
		Details:   details,
		RequestID: requestIDFromRequest(r),
	})
}
