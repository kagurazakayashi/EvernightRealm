// Package rootinit 提供 Root 憑據的「一次性初始化」、口令遺失後的本機恢復，與最小狀態查詢。
//
// 為什麼單獨成包（而不是寫在 app 的 CLI 檔裡）：入口層不該裝領域規則，
// 而「只在尚無憑據時寫得進去、寫進去之後永久關上」與「只換已有的那一份、絕不順手建立」
// 這兩條規則需要被 CLI 以外的呼叫端（未來的安裝精靈）以同一個形狀重用。
// 這一層因此只認三件事：組態檔路徑、交上來的口令明文、生效的雜湊參數檔。
//
// 邊界（刻意不做的事）：
//   - 不開 HTTP 端點、不認請求內容：初始化的授權邊界是「能在伺服器本機執行命令的人」，
//     CORS、來源_ip、瀏覽器顯示什麼都與這個判斷無關，把它們當依據等於假裝有把關；
//   - 不產生「公開的預設口令」、不寫明文、不把口令另存一份到資料庫：
//     Root 的持久形態只有組態檔裡那個 Argon2id 編碼；
//   - 不管跨進程互斥：那由資料庫的單寫入實例鎖負責（見 app 層的 init-root 與
//     recover-root 子命令），本套件只保證「同一進程內併發也只有一次成功」；
//   - 不做改密、不做登入、不發會話：改密是「已認證情況下先交出現行口令」的另一條路，
//     會話則由 internal/auth 簽發。這裡只回答「現在有沒有 Root」、「把口令放進去」
//     與「把已有的那份換掉（且不問舊口令）」。
//
// 失敗的形態只有「回傳錯誤且組態檔維持原樣」一種：寫入路徑的任何中斷都發生在
// 同目錄的臨時檔上，因此不存在「回了成功但沒落地」或「檔案是半份」的狀態。
//
// 本包對「恢復後舊會話怎麼辦」「這次嘗試要不要進 Root 審計」完全不知情：
// 那是資料庫與裝配層的事（見 internal/app/recover_root.go）。
