// Package session 提供服务端会话的领域模型、不透明秘密与持久仓储：
// 创建、验证、撤销三个动作构成它的全部生命周期入口。
//
// 为什么要有这个套件（ER-SEC-001 的会话要求、DEC-032 的统一可信身份取向）：
// 登录态是整台服务器的授权起点——「现在这个请求是谁」如果每个模块各自记一份，
// 就会出现「会话还在、账户已禁用还能操作」这类分裂答案。本套件把答案收敛成一处：
//   - 会话关联的是 internal/identity 的受信主体（Root 或账户），不是自报的字符串；
//   - 验证在每次通过前都重读主体的当前状态，会话行存在不代表主体有效；
//   - 撤销只改一行、立即生效，没有「缓存了旧会话还能再用一会儿」的第二通路。
//
// 三个标识严格分工（互不顶替，混用即缺陷）：
//   - ID：内部会话标识（UUIDv7 主键），供参照与运维定位，不承担认证；
//   - DeviceID：用户可见设备标识（独立随机 UUIDv7），展示与按设备撤销用，
//     泄露它也换不来任何操作能力；
//   - 秘密（secret）：密码学安全随机、只在创建时回传一次的认证材料；
//     库里只有它的 SHA-256，数据库整档外泄也造不出可用会话。
//
// 本套件刻意不做的事（边界，不是遗漏）：
//   - 不开任何 HTTP／WebSocket 端点，也不写登录流程——凭据校验属登录用例，
//     它成功后才调用这里的 Create；口令更换、设备策略、会话轮换都复用同一入口。
//   - 不在会话里存角色或权限：权限每次由服务端从授权资料现读（internal/identity），
//     会话只回答「是谁」，不回答「能做什么」。存了权限的会话会在改授权之后继续放行，
//     那是比不存更糟的过期快照。
//   - 不维护审计记录本身：Create/Verify/Revoke 都接受呼叫端传入的 Querier，
//     未来的登录用例据此把「会话写入 + 审计追加」放进同一交易（DEC-013），
//     审计失败整体回滚，不会留下无声的特权会话；本包也绝不会在会话写入失败时
//     留下「登录成功」的假象。
//   - 不做过期清理：到期只在验证时拒绝，物理删除属未来的清理任务。
package session
