-- 活動級「玩家自選陣營」開關（活動內業務第三步：把「玩家能不能自己選陣營」釘在活動那一行上）。
--
-- 表結構約定（DEC-011）：一般表（非 STRICT）；本支只 ADD COLUMN，不改寫任何舊行、
-- 不重建表、不動 0012 已落地的欄位與觸發器。
--
-- 為什麼這一欄落在 activities 而不是 activity_factions 或一張新的設定表：
--   「這場活動開不開放玩家自己選」是一場活動的屬性，判定只該有一個地方讀它。
--   落在陣營那一側會變成「開關是每個陣營各一欄」，於是「這場活動有沒有開放」要掃全場
--   陣營才知道，而停用旗標（0013 的 available）已經佔了「這一個陣營能不能進人」那句話——
--   兩欄互相解釋等於兩套真相。落在獨立設定表則要為一行布爾值多開一張表與一套讀寫，
--   而它與活動同生同滅、永不單獨存在，沒有那個必要。
--
-- 三態而不是布林（本輪用戶決定）：
--   disabled（預設）：完全不開放玩家自選；陣營歸屬只由管理側通路決定。
--   first_only：玩家可以自己選第一次，選定之後自助通路不再改變他的歸屬。
--   free：玩家可以在可用陣營之間反覆自選。
--   理由是用戶批準的那句邊界：「允許自選」不等於「可以無限次切換」，也不是「選錯就一輩子」。
--   三個語意各有真實的部署場景，收進一枚列舉就把「切換次數規則」寫成一個地方讀得到的事實，
--   而不是散在各端點裡的 if。本步沒有加人數配額、付費切換、冷卻或審批——那些都不是被批準的規則。
--
-- 出廠值是 disabled 而且是 DEFAULT（本輪用戶批準的相容規則）：
--   ALTER TABLE ADD COLUMN 的 DEFAULT 讓既有每一行自動讀成「沒開放」，於「新功能不得未經批準
--   就向所有舊活動開放」成立在遷移形狀上：本支不回填任何「已開放」的語意，也不需要一份
--   舊活動清單。管理人若要開放，必須在活動配置裡明確選一個非 disabled 的值。
--   把預設設成 free 或 first_only 等於在用戶不知情時把玩家的寫入入口開到每一場活動上。
--
-- CHECK 是封閉集合（口徑同 0012 的 status 與 0013 的 icon）：
--   新增取值一律走新的遷移放寬清單，讓「玩家能怎麼選」的改變必然在版本史上留痕。
--   SQLite 的 ADD COLUMN 可以帶表內 CHECK：新欄的 CHECK 對其後的每一次插入與更新生效，
--   而既有行由 DEFAULT 直接落在集合內（有定向測試釘住這兩件事，不靠「應該如此」）。
--
-- 這是一欄配置，不是生命週期狀態：
--   它不進 status 那四態——把「開放自選」寫成活動狀態會讓「這件事進行到哪裡」失去意義
--   （口徑同 0012 檔頭對階段／調度的說明）。它也不約束陣營本身能不能被使用：
--   「這個陣營此刻收不收新成員」只由 0013 的 available 與活動的業務寫入門禁決定
--   （見 internal/activity 的 EnsureFactionAcceptsNewMembers）。
--
-- 沒有刪除通路，也沒有「清回未設定」：disabled 就是那個可逆的關閉態，
--   改回來只改這一欄；玩家在 first_only 下已經落下的歸屬不因改開關而被清空
--   （保留歸屬是 0013 停用語意同樣的態度：開關只約束往後能不能發生，不改寫已經發生的事實）。

ALTER TABLE activities ADD COLUMN faction_select_mode TEXT NOT NULL DEFAULT 'disabled'
    CHECK (faction_select_mode IN ('disabled', 'first_only', 'free'));
